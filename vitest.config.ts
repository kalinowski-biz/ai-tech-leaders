import { fileURLToPath } from 'node:url'
import { defineConfig } from 'vitest/config'
import { defineVitestProject } from '@nuxt/test-utils/config'

/**
 * Unit tests (`pnpm test`, `pnpm test:coverage`). They never need Docker or a
 * database; integration tests live in `vitest.integration.config.ts`.
 *
 * `*.test.ts` runs in plain Node; `*.nuxt.test.ts` (components, composables,
 * pages) runs inside the Nuxt runtime (`@nuxt/test-utils`, happy-dom).
 */
const NUXT_TESTS = 'packages/app/{app,server,shared}/**/*.nuxt.test.ts'
const APP_ROOT = fileURLToPath(new URL('packages/app', import.meta.url))

export default defineConfig({
  test: {
    projects: [
      { test: { name: 'core', environment: 'node', include: ['packages/core/src/**/*.test.ts'] } },
      { test: { name: 'database', environment: 'node', include: ['packages/database/src/**/*.test.ts'] } },
      {
        test: {
          name: 'app',
          environment: 'node',
          // Nuxt's `#shared` alias, for server code tested outside the Nuxt runtime.
          alias: { '#shared': fileURLToPath(new URL('packages/app/shared', import.meta.url)) },
          include: ['packages/app/{app,server,shared}/**/*.test.ts'],
          exclude: [NUXT_TESTS],
        },
      },
      await defineVitestProject({
        // Rooted at the app so Vite resolves Nuxt's runtime files like `nuxt dev` does.
        root: APP_ROOT,
        test: {
          name: 'app-nuxt',
          include: ['{app,server,shared}/**/*.nuxt.test.ts'],
          environment: 'nuxt',
          setupFiles: ['test/setup.nuxt.ts'],
          environmentOptions: { nuxt: { rootDir: APP_ROOT, domEnvironment: 'happy-dom' } },
        },
      }),
    ],
    coverage: {
      provider: 'v8',
      // Every hand-written source file counts, tested or not (AGENTS.md: 100 % unit coverage).
      include: [
        'packages/core/src/**/*.ts',
        'packages/database/src/**/*.ts',
        'packages/app/{app,server,shared}/**/*.{ts,vue}',
      ],
      exclude: [
        '**/*.test.ts',
        '**/*.d.ts',
        // Generated by shadcn-vue (AGENTS.md "Frontend conventions"); covered through the components using them.
        'packages/app/app/components/ui/**',
      ],
      reporter: ['text', 'html', 'lcov', 'json-summary'],
      reportsDirectory: 'coverage',
      thresholds: { lines: 100, statements: 100, functions: 100, branches: 100 },
    },
  },
})
