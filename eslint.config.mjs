import { createConfigForNuxt } from '@nuxt/eslint-config'
import prettier from 'eslint-config-prettier'

/**
 * Package boundaries (see docs/engineering-standards.md, "Architecture").
 * `core` is framework-free; `database` never reaches into the app; the Vue
 * side of the app never touches the ORM, the container or raw fetch.
 */
function restrictImports(...patterns) {
  return ['error', { patterns }]
}

function frameworkImports() {
  return {
    group: ['nuxt', 'nuxt/*', '#imports', '#app', 'vue', 'vue-router', 'h3', 'nitropack', 'nitropack/*'],
    message: 'Framework imports belong in packages/app only.',
  }
}

export default createConfigForNuxt({
  features: { typescript: { strict: true }, stylistic: false },
  dirs: {
    src: ['packages/app/app'],
    root: ['packages/app'],
    pages: ['packages/app/app/pages'],
    layouts: ['packages/app/app/layouts'],
    components: ['packages/app/app/components'],
    composables: ['packages/app/app/composables', 'packages/app/app/utils'],
    plugins: ['packages/app/app/plugins'],
    middleware: ['packages/app/app/middleware'],
    servers: ['packages/app/server'],
  },
})
  .prepend({
    ignores: [
      '**/.nuxt/**',
      '**/.output/**',
      '**/dist/**',
      '.ai/**',
      'local/**',
      // Generated by shadcn-vue; do not lint (see AGENTS.md "Frontend conventions").
      'packages/app/app/components/ui/**',
    ],
  })
  .append(
    {
      name: 'tripsalesagent/boundaries/core',
      files: ['packages/core/**/*.ts'],
      rules: {
        'no-restricted-imports': restrictImports(
          {
            group: ['@tripsalesagent/database', '@tripsalesagent/app'],
            message: 'core must not depend on database or app – declare a port instead.',
          },
          { group: ['@mikro-orm/*'], message: 'core must not depend on the ORM – use a repository port.' },
          frameworkImports(),
        ),
      },
    },
    {
      name: 'tripsalesagent/boundaries/database',
      files: ['packages/database/**/*.ts'],
      rules: {
        'no-restricted-imports': restrictImports(
          { group: ['@tripsalesagent/app'], message: 'database must not depend on app.' },
          frameworkImports(),
        ),
      },
    },
    {
      name: 'tripsalesagent/boundaries/app-client',
      files: ['packages/app/app/**/*.{ts,vue}'],
      rules: {
        'no-restricted-imports': restrictImports({
          group: ['@tripsalesagent/database', '@mikro-orm/*', 'awilix'],
          message: 'Client code never touches the ORM or the container; call the API through useApi().',
        }),
        'no-restricted-syntax': [
          'error',
          ...['$fetch', 'fetch', 'useFetch', 'useLazyFetch'].map((name) => ({
            selector: `CallExpression[callee.name='${name}']`,
            message: `Do not call ${name}() directly; use useApi() / useApiQuery().`,
          })),
        ],
      },
    },
    {
      name: 'tripsalesagent/boundaries/app-client-api',
      files: ['packages/app/app/composables/useApi.ts', 'packages/app/app/composables/useApiQuery.ts'],
      rules: { 'no-restricted-syntax': 'off' },
    },
    {
      name: 'tripsalesagent/quality',
      rules: {
        'no-console': ['error', { allow: ['warn', 'error'] }],
        '@typescript-eslint/no-explicit-any': 'error',
        '@typescript-eslint/no-unused-vars': ['error', { argsIgnorePattern: '^_', varsIgnorePattern: '^_' }],
        'no-empty': ['error', { allowEmptyCatch: false }],
        // Optional TS props are `undefined` by design; defaults only where they carry meaning.
        'vue/require-default-prop': 'off',
      },
    },
    prettier,
  )
