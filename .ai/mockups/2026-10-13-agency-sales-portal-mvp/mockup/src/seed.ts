function history(...entries: Array<[string, string, HistoryEntry['channel'], string, string?]>): HistoryEntry[] {
  return entries.map(([at, actor, channel, label, comment]) => ({ at, actor, channel, label, comment: comment ?? '' }));
}

function commission(status: Commission['status'], rate: number, baseValue: number, paidOn: string | null = null): Commission {
  return {
    status,
    rate,
    baseValue,
    amount: status === 'CANCELLED' ? 0 : Math.round(baseValue * rate) / 100,
    paidOn,
    history: [],
  };
}

